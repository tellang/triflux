describe("감사 정탐은 유지한다", () => {
  // 공백 제외 12자 이하는 짧은 반응 가드(E)가 거르므로 정탐 예시는 그보다 길다.
  for (const prompt of [
    "결제 화면에 로그인 기능 구현해줘",
    "목록 정렬하는 이 함수 버그 좀 고쳐줘",
    "implement the parser",
    "스킬에 버그가 있었다면 직접 수정해줘",
  ]) {
    it(`${prompt} → tfx-auto suggest`, () => {
      const context = contextOf(prompt);
      assert.match(context, /^\[TRIFLUX SKILL SUGGESTION: tfx-unified\]/);
      assert.match(
        context,
        /코드 구현·수정 실행 요청이면 Skill 도구로 tfx-auto/,
      );
      assert.match(context, /질문·상태 확인·대화·다른 도메인이면/);
      assert.doesNotMatch(context, /MUST/);
    });
  }

  it("이 작업 tfx-auto 로 돌려줘 → MUST 호출", () => {
    const context = contextOf("이 작업 tfx-auto 로 돌려줘");
    assert.match(context, /^\[TRIFLUX MAGIC KEYWORD: tfx-unified\]/);
    assert.match(context, /You MUST invoke the skill/);
    assert.match(context, /Skill: tfx-auto/);
  });

  it("문장 중간 /tfx-harness 는 MUST 호출 (호스트가 확장하지 않는다)", () => {
    const context = contextOf(
      "이번 건은 /tfx-harness 로 어떤 경로가 맞는지 판정해줘",
    );
    assert.match(context, /^\[TRIFLUX MAGIC KEYWORD: tfx-harness\]/);
    assert.match(context, /Skill: tfx-harness/);
  });

  it("짧아도 문장 중간 /tfx- 토큰이 있으면 짧은 반응으로 보지 않는다", () => {
    assert.match(contextOf("그럼 /tfx-auto 로"), /Skill: tfx-auto/);
  });

  it("슬래시 없는 이름 언급은 주입하지 않는다", () => {
    for (const prompt of [
      "그건 이미 tfx-auto에 합쳐졌을텐데 맞지",
      "tfx-harness? tfx-auto? 뭐가 기본 진입점이었더라",
    ]) {
      assert.equal(contextOf(prompt), undefined, prompt);
    }
  });

  it("triflux repo 에서 버전 올려서 릴리즈하고 → tfx-ship 제안", () => {
    const context = contextOf(
      "버전 올려서 릴리즈하고 로컬에도 반영해줘",
      {},
      TRIFLUX_CWD,
    );
    assert.match(context, /^\[TRIFLUX SKILL SUGGESTION: tfx-ship\]/);
  });

  it("주입문은 프롬프트 원문과 OMC 무시 지시를 싣지 않는다", () => {
    for (const prompt of [
      "이 작업 tfx-auto 로 돌려줘",
      "결제 화면에 로그인 기능 구현해줘",
    ]) {
      const context = contextOf(prompt);
      assert.doesNotMatch(context, /User request:/);
      assert.ok(!context.includes(prompt), "프롬프트 원문이 다시 붙었습니다");
      assert.doesNotMatch(context, /\[MAGIC KEYWORD:\]/);
      assert.doesNotMatch(context, /PRIORITY:/);
    }
  });
});

