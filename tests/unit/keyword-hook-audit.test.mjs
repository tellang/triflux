const ROOT = process.cwd();
const DETECTOR = join(ROOT, "scripts", "keyword-detector.mjs");

const tempDirs = [];
function tempDir() {
  const dir = mkdtempSync(join(tmpdir(), "kw-audit-"));
  tempDirs.push(dir);
  return dir;
}
after(() => {
  for (const dir of tempDirs) rmSync(dir, { recursive: true, force: true });
});

// gstack 스킬 설치 이름을 흉내 내는 임시 스킬 루트 (접두사 없음 / 있음).
function skillRoot(names) {
  const root = tempDir();
  for (const name of names) {
    mkdirSync(join(root, name), { recursive: true });
    writeFileSync(join(root, name, "SKILL.md"), `---\nname: ${name}\n---\n`);
  }
  return root;
}
const PLAIN_GSTACK = skillRoot(["ship", "retro", "context-restore"]);
// triflux repo_scope 판정용 cwd (path segment 에 triflux 포함).
const TRIFLUX_CWD = join(ROOT, "..", "triflux", "work");

function runDetector(prompt, env = {}, cwd = ROOT) {
  const result = spawnSync(process.execPath, [DETECTOR], {
    input: JSON.stringify({ prompt, cwd }),
    encoding: "utf8",
    env: {
      ...process.env,
      TRIFLUX_DISABLE_MAGICWORDS: "",
      TRIFLUX_SKILL_ROOTS: PLAIN_GSTACK,
      ...env,
    },
  });
  assert.equal(result.status, 0, result.stderr);
  return JSON.parse(result.stdout.trim());
}

function contextOf(prompt, env, cwd) {
  return runDetector(prompt, env, cwd)?.hookSpecificOutput?.additionalContext;
}

function writeRules(rules) {
  const file = join(tempDir(), "rules.json");
  writeFileSync(file, JSON.stringify({ rules }), "utf8");
  return file;
}

