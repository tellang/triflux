describe("exclude_patterns / strength 규칙 필드", () => {
  const fixture = () =>
    writeRules([
      {
        id: "mixed",
        patterns: [
          { source: "\\bfoo-skill\\b", flags: "i", strength: "explicit" },
          { source: "바꿔", flags: "" },
        ],
        exclude_patterns: [{ source: "[?]\\s*$", flags: "" }],
        skill: "foo-skill",
        priority: 1,
        strength: "suggest",
        suggest_when: "푸 작업 실행 요청",
      },
      {
        id: "plain",
        patterns: [{ source: "bar", flags: "i" }],
        skill: "bar-skill",
        priority: 2,
      },
    ]);

  it("규칙 기본 strength 는 explicit, 패턴별 strength 가 덮어쓴다", () => {
    const rules = loadRules(fixture());
    const mixed = rules.find((r) => r.id === "mixed");
    assert.equal(mixed.strength, "suggest");
    assert.deepEqual(
      mixed.patterns.map((p) => p.strength),
      ["explicit", "suggest"],
    );
    assert.equal(rules.find((r) => r.id === "plain").strength, "explicit");
  });

  it("suggest 매칭은 exclude_patterns 에 걸리면 빠진다", () => {
    const compiled = compileRules(loadRules(fixture()));
    assert.equal(matchRules(compiled, "이거 바꿔")[0]?.strength, "suggest");
    assert.deepEqual(matchRules(compiled, "이거 바꿔?"), []);
  });

  it("명시 토큰 매칭은 exclude_patterns 와 무관하게 explicit 로 남는다", () => {
    const compiled = compileRules(loadRules(fixture()));
    const [match] = matchRules(compiled, "foo-skill 로 바꿔?");
    assert.equal(match?.id, "mixed");
    assert.equal(match?.strength, "explicit");
  });

  it("잘못된 strength·exclude_patterns 는 규칙을 무효로 본다", () => {
    const file = writeRules([
      {
        id: "bad-strength",
        patterns: [{ source: "a", flags: "" }],
        skill: "x",
        priority: 1,
        strength: "must",
      },
      {
        id: "bad-exclude",
        patterns: [{ source: "a", flags: "" }],
        exclude_patterns: "nope",
        skill: "x",
        priority: 1,
      },
      {
        id: "ok",
        patterns: [{ source: "a", flags: "" }],
        skill: "x",
        priority: 1,
      },
    ]);
    assert.deepEqual(
      loadRules(file).map((r) => r.id),
      ["ok"],
    );
  });

  it("suggest 주입문은 suggest_when 을 조건으로 쓴다", () => {
    const context = contextOf("이 문단 전체를 조금 더 다른 말로 바꿔", {
      TRIFLUX_KEYWORD_RULES_PATH: fixture(),
    });
    assert.match(context, /^\[TRIFLUX SKILL SUGGESTION: mixed\]/);
    assert.match(context, /푸 작업 실행 요청이면 Skill 도구로 foo-skill/);
  });

  it("context_hint 주입문에 Windows 전용 wt.exe 문구가 붙지 않는다", () => {
    const file = writeRules([
      {
        id: "hint-rule",
        patterns: [{ source: "hinty-keyword", flags: "i" }],
        action: "context_hint",
        hint: "범용 힌트",
        priority: 1,
      },
    ]);
    const context = contextOf("please apply hinty-keyword now", {
      TRIFLUX_KEYWORD_RULES_PATH: file,
    });
    assert.equal(context, "[TRIFLUX CONTEXT HINT: hint-rule]\n\n범용 힌트");
  });
});

describe("hooks/keyword-rules.json 감사 반영", () => {
  const rules = loadRules(join(ROOT, "hooks", "keyword-rules.json"));

  it("맨명사 MCP 라우트·handoff·사용 0회 토큰 규칙이 없다", () => {
    const ids = new Set(rules.map((r) => r.id));
    for (const id of [
      "chrome-route",
      "mail-route",
      "calendar-route",
      "github-route",
      "confluence-route",
      "notion-route",
      "jira-route",
      "slack-route",
      "playwright-route",
      "canva-route",
      "handoff-route",
      "tfx-analysis",
      "tfx-prune",
      "tfx-hub",
    ]) {
      assert.equal(ids.has(id), false, `${id} 가 남아 있다`);
    }
  });

  it("gstack-checkpoint 는 실제 스킬 이름 context-restore 를 가리키고 맨 resume 을 잡지 않는다", () => {
    const rule = rules.find((r) => r.id === "gstack-checkpoint");
    assert.deepEqual(rule.skill_candidates, [
      "context-restore",
      "gstack-context-restore",
    ]);
    const compiled = compileRules(rules);
    assert.equal(
      matchRules(compiled, "resume the download").some(
        (m) => m.id === "gstack-checkpoint",
      ),
      false,
    );
  });

  it("host-ai-slop-cleaner 는 맨 '클린업'·'슬롭'을 잡지 않는다", () => {
    const compiled = compileRules(rules);
    for (const text of ["클린업 해줘", "슬롭 정리"]) {
      assert.equal(
        matchRules(compiled, text).some((m) => m.id === "host-ai-slop-cleaner"),
        false,
        text,
      );
    }
  });

  it("suppress-omc-team 은 맨 '팀' 을 잡지 않는다", () => {
    const compiled = compileRules(rules);
    for (const text of [
      "우리 팀 회의",
      "팀장님 메일",
      "레드팀으로 공격 시나리오 짜보자",
      "개발팀 구성 현황 알려줘",
      "팀 저장소 구성 정리",
      "이건 /team 으로 돌려",
    ]) {
      assert.equal(
        matchRules(compiled, text).some((m) => m.id === "suppress-omc-team"),
        false,
        text,
      );
    }
    assert.ok(
      matchRules(compiled, "팀 모드로 돌려").some(
        (m) => m.id === "suppress-omc-team",
      ),
    );
  });
});

describe("gstack 스킬 설치 이름 해석 (머신별 접두사)", () => {
  it("resolveInstalledSkill: 후보 중 설치된 첫 이름, 없으면 null", () => {
    const prefixed = skillRoot(["gstack-ship"]);
    assert.equal(
      resolveInstalledSkill(["ship", "gstack-ship"], [PLAIN_GSTACK]),
      "ship",
    );
    assert.equal(
      resolveInstalledSkill(["ship", "gstack-ship"], [prefixed]),
      "gstack-ship",
    );
    assert.equal(
      resolveInstalledSkill(["ship", "gstack-ship"], [tempDir()]),
      null,
    );
  });

  const retroPrompt = "이번 주 회고 해보자 뭐가 잘 됐는지 정리해서";

  it("접두사 설치 머신에서는 gstack-retro 로 주입한다", () => {
    const context = contextOf(retroPrompt, {
      TRIFLUX_SKILL_ROOTS: skillRoot(["gstack-retro"]),
    });
    assert.match(context, /Skill 도구로 gstack-retro 을 고려하라/);
  });

  it("접두사 없는 머신에서는 retro 로 주입한다", () => {
    assert.match(contextOf(retroPrompt), /Skill 도구로 retro 을 고려하라/);
  });

  it("후보가 하나도 설치되지 않았으면 주입하지 않는다", () => {
    assert.equal(
      contextOf(retroPrompt, { TRIFLUX_SKILL_ROOTS: tempDir() }),
      undefined,
    );
  });

  it("gstack-retro 는 회고 문서·회의 요청을 잡지 않는다", () => {
    for (const prompt of [
      "회고 템플릿 찾아서 이번 주 회고 문서 써줘",
      "지난 주 회고 회의 내용 전사해줘",
    ]) {
      assert.equal(contextOf(prompt), undefined, prompt);
    }
  });

  it("gstack-ship 은 맨 '배포해' 를 잡지 않고 PR 표현만 받는다", () => {
    const compiled = compileRules(
      loadRules(join(ROOT, "hooks", "keyword-rules.json")),
    );
    const ids = (t) => matchRules(compiled, t).map((m) => m.id);
    assert.ok(!ids("dev 서버에 배포해 봐").includes("gstack-ship"));
    assert.ok(ids("이 브랜치로 PR 올려줘").includes("gstack-ship"));
    assert.ok(ids("looks good, ship it").includes("gstack-ship"));
    assert.ok(!ids("PR 올려도 되나?").includes("gstack-ship"));
  });
});
