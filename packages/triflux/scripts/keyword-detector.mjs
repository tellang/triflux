#!/usr/bin/env node

import {
  existsSync,
  mkdirSync,
  readFileSync,
  realpathSync,
  writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import { delimiter, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  compileRules,
  loadRules,
  matchRules,
  resolveConflicts,
} from "./lib/keyword-rules.mjs";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = dirname(SCRIPT_DIR);
const DEFAULT_RULES_PATH = join(PROJECT_ROOT, "hooks", "keyword-rules.json");

function readHookInput() {
  try {
    return readFileSync(0, "utf8");
  } catch {
    return "";
  }
}

function parseInput(rawInput) {
  try {
    return JSON.parse(rawInput);
  } catch {
    return null;
  }
}

// prompt > message.content > parts[].text 우선순위로 추출
export function extractPrompt(payload) {
  if (!payload || typeof payload !== "object") return "";

  if (typeof payload.prompt === "string" && payload.prompt.trim()) {
    return payload.prompt;
  }

  if (
    typeof payload.message?.content === "string" &&
    payload.message.content.trim()
  ) {
    return payload.message.content;
  }

  if (Array.isArray(payload.message?.content)) {
    const messageText = payload.message.content
      .map((part) => {
        if (typeof part === "string") return part;
        if (part && typeof part.text === "string") return part.text;
        return "";
      })
      .filter(Boolean)
      .join(" ")
      .trim();
    if (messageText) return messageText;
  }

  if (Array.isArray(payload.parts)) {
    const partsText = payload.parts
      .map((part) => {
        if (typeof part === "string") return part;
        if (part && typeof part.text === "string") return part.text;
        return "";
      })
      .filter(Boolean)
      .join(" ")
      .trim();
    if (partsText) return partsText;
  }

  return "";
}

// 프롬프트가 슬래시 명령(/resume, /tfx-auto, /oh-my-claudecode:team, /loop …)으로
// 시작하면 호스트가 이미 명령·스킬을 실행하므로 키워드 주입을 하지 않는다.
// 명령 이름 뒤에 공백이나 끝이 와야 한다 — "/Users/x 고쳐줘" 같은 절대 경로는 명령이 아니다.
export function isSlashCommandPrompt(text) {
  if (typeof text !== "string") return false;
  return /^\s*\/[\w:.-]+(?=\s|$)/.test(text);
}

// 붙여넣기 블록을 뺀, 사용자가 직접 친 텍스트.
export function stripPastedContent(text) {
  if (typeof text !== "string") return "";
  return text.replace(
    /<pasted_content\b[^>]*>[\s\S]*?<\/pasted_content\b[^>]*>/g,
    " ",
  );
}

// 다른 에이전트·도구가 만든 프롬프트(핸드오프 continuation, 팀 리드 부트스트랩,
// tfx-live 중계 토픽 같은 대문자 태그)는 사용자 지시가 아니다.
const AUTO_GENERATED_PROMPT =
  /^\s*(?:Continuation (?:skills|contract)\b|-\s*Handoff envelope|리드 에이전트:|[A-Z][A-Z0-9_]{7,}[:\s])|Continuation contract:/;

export function isAutoGeneratedPrompt(ownText) {
  return typeof ownText === "string" && AUTO_GENERATED_PROMPT.test(ownText);
}

// 짧은 반응("진행해", "좋아 해봐")은 진행 중 작업에 대한 대답이다. 문장 중간의
// 슬래시 명시 토큰(/tfx-…)이 있으면 짧아도 호출로 본다.
export function isShortReaction(ownText) {
  if (typeof ownText !== "string") return true;
  return (
    ownText.replace(/\s/g, "").length <= 12 &&
    !/(?<![\w/.-])\/tfx-/.test(ownText)
  );
}

// 머신마다 설치 이름이 다른 스킬(gstack `ship` / `gstack-ship`)의 탐색 경로.
// TRIFLUX_SKILL_ROOTS(경로 구분자 목록)가 있으면 그것만 본다.
export function defaultSkillRoots(baseDir) {
  if (process.env.TRIFLUX_SKILL_ROOTS) {
    return process.env.TRIFLUX_SKILL_ROOTS.split(delimiter).filter(Boolean);
  }
  const configDir = process.env.CLAUDE_CONFIG_DIR || join(homedir(), ".claude");
  const roots = [join(configDir, "skills")];
  if (typeof baseDir === "string" && baseDir) {
    roots.unshift(join(baseDir, ".claude", "skills"));
  }
  return roots;
}

// 후보 중 실제 설치된 첫 스킬 이름. 하나도 없으면 null(주입 생략).
export function resolveInstalledSkill(candidates, roots) {
  if (!Array.isArray(candidates) || !Array.isArray(roots)) return null;
  for (const name of candidates) {
    for (const root of roots) {
      if (existsSync(join(root, name, "SKILL.md"))) return name;
    }
  }
  return null;
}

// 키워드 오탐 방지를 위해 XML/URL/파일경로/코드블록/인용문 제거
export function sanitizeForKeywordDetection(text) {
  if (typeof text !== "string" || !text) return "";

  return (
    text
      .replace(/```[\s\S]*?```/g, " ")
      .replace(/`[^`]*`/g, " ")
      // 스킬 선언 목록 줄(- /tfx-x — 설명)은 지시가 아니라 목록이다.
      .replace(/^\s*[-*]\s*\/[\w:.-]+\s*[—–-]\s.*$/gm, " ")
      // 줄 머리 `>` 인용문(남의 글·이전 출력 인용)은 사용자 지시가 아니다.
      .replace(/^[ \t]*>.*$/gm, " ")
      // 닫는 태그에 속성이 붙은 형태(</pasted_content id="1">)도 짝으로 지운다.
      .replace(/<(\w[\w:-]*)(?:\s[^>]*)?>[\s\S]*?<\/\1(?:\s[^>]*)?>/g, " ")
      .replace(/<\w[\w:-]*(?:\s[^>]*)?\/>/g, " ")
      .replace(/https?:\/\/[^\s)>\]]+/gi, " ")
      .replace(/\b[A-Za-z]:\\(?:[^\\\s]+\\)*[^\\\s]*/g, " ")
      .replace(/(^|[\s"'`(])~\/\S*/g, "$1 ")
      .replace(/(^|[\s"'`(])(?:\/|\.{1,2}\/)?(?:[\w.-]+\/)+[\w.-]+/gm, "$1 ")
      .replace(/\s+/g, " ")
      .trim()
  );
}

// repo_scope 는 path segment 단위로 매칭한다 — "triflux" 는 .../tools/triflux/... 에만
// 매칭되고 .../triflux-ideas 같은 부분 문자열에는 매칭되지 않는다. 빈 scope = 전역.
export function matchesRepoScope(path, scopes) {
  if (!Array.isArray(scopes) || scopes.length === 0) return true;
  if (typeof path !== "string" || !path) return false;
  const segments = path.split(/[\\/]+/).filter(Boolean);
  return scopes.some((scope) => segments.includes(scope));
}

// platform 은 규칙의 정적 속성이라 cwd 의존인 repo_scope 와 달리 매칭 이전에
// 거른다. resolveConflicts 뒤에 걸면 Windows 전용 규칙이 supersedes 로 다른
// 규칙을 죽인 다음 자신도 빠져 매칭 결과가 통째로 비어버린다.
export function matchesPlatform(platforms, currentPlatform) {
  if (!Array.isArray(platforms) || platforms.length === 0) return true;
  return platforms.includes(currentPlatform);
}

// resolvedMatches[0] 단일 승자의 우선순위 역전 방지.
// 1) 명시 토큰(strength explicit) 매칭이 하나라도 있으면 그 안에서만 고른다 —
//    사용자가 직접 부른 스킬이 자연어 제안(suggest)에 밀리지 않는다.
// 2) 그 후보 안에서 explicit(종결 라우팅) 규칙이 정렬 순서와 무관하게 이긴다.
//    없으면 정렬 선두 유지. strength 가 없는 매치는 explicit 로 본다.
export function selectPrimaryMatch(resolvedMatches) {
  if (!Array.isArray(resolvedMatches) || resolvedMatches.length === 0) {
    return null;
  }
  const strong = resolvedMatches.filter(
    (match) => match?.strength !== "suggest",
  );
  const pool = strong.length > 0 ? strong : resolvedMatches;
  const explicitMatch = pool.find((match) => match?.explicit === true);
  return explicitMatch ?? pool[0];
}

function createHookOutput(additionalContext) {
  return {
    continue: true,
    hookSpecificOutput: {
      hookEventName: "UserPromptSubmit",
      additionalContext,
    },
  };
}

function createSuppressOutput() {
  return { continue: true, suppressOutput: true };
}

// 명시 토큰 → MUST 호출. 프롬프트 원문은 이미 대화에 있으므로 다시 붙이지 않는다.
function createSkillContext(match) {
  return `[TRIFLUX MAGIC KEYWORD: ${match.id}]

You MUST invoke the skill using the Skill tool:
Skill: ${match.skill}

IMPORTANT: Invoke the skill IMMEDIATELY. Do not proceed without loading the skill instructions.`;
}

// 자연어 매칭 → 제안. 강제하지 않고 요청 성격을 Claude 가 판정하게 둔다.
function createSkillSuggestion(match) {
  const when = match.suggest_when || "이 스킬이 맡는 작업의 실행 요청";
  return `[TRIFLUX SKILL SUGGESTION: ${match.id}]

${when}이면 Skill 도구로 ${match.skill} 을 고려하라.
질문·상태 확인·대화·다른 도메인이면 이 제안을 무시하라.`;
}

function createContextHintOutput(match) {
  return `[TRIFLUX CONTEXT HINT: ${match.id}]

${match.hint}`;
}

function createSuppressOmcContext(match) {
  return `[TRIFLUX OMC SUPPRESS: ${match.id}]

이 키워드는 TRIFLUX가 관리한다. 이 프롬프트 때문에 OMC 스킬을 자동 호출하지 말고 요청을 일반적으로 처리하라.`;
}

function createMcpRouteContext(match) {
  return `[TRIFLUX MCP ROUTE: ${match.mcp_route}]

이 작업은 ${match.mcp_route}로 라우팅해야 합니다.
tfx-route.sh를 통해 ${match.mcp_route}로 실행하세요.`;
}

function isSkipRequested() {
  if (process.env.TRIFLUX_DISABLE_MAGICWORDS === "1") return true;
  const skipHooks = (process.env.TRIFLUX_SKIP_HOOKS || "")
    .split(",")
    .map((item) => item.trim())
    .filter(Boolean);
  return skipHooks.includes("keyword-detector");
}

function activateState(baseDir, stateConfig, prompt, payload) {
  if (!stateConfig || stateConfig.activate !== true || !stateConfig.name)
    return;

  try {
    const stateRoot = join(baseDir, ".triflux", "state");
    mkdirSync(stateRoot, { recursive: true });

    const sessionId =
      typeof payload?.session_id === "string"
        ? payload.session_id
        : typeof payload?.sessionId === "string"
          ? payload.sessionId
          : "";

    let stateDir = stateRoot;
    if (sessionId && /^[a-zA-Z0-9][a-zA-Z0-9_-]{0,255}$/.test(sessionId)) {
      stateDir = join(stateRoot, "sessions", sessionId);
      mkdirSync(stateDir, { recursive: true });
    }

    const statePath = join(stateDir, `${stateConfig.name}-state.json`);
    const statePayload = {
      active: true,
      name: stateConfig.name,
      started_at: new Date().toISOString(),
      original_prompt: prompt,
    };

    writeFileSync(statePath, JSON.stringify(statePayload, null, 2), "utf8");
  } catch (error) {
    console.error(
      `[triflux-keyword-detector] 상태 저장 실패: ${error.message}`,
    );
  }
}

function getRulesPath() {
  if (process.env.TRIFLUX_KEYWORD_RULES_PATH) {
    return process.env.TRIFLUX_KEYWORD_RULES_PATH;
  }
  return DEFAULT_RULES_PATH;
}

function main() {
  if (isSkipRequested()) {
    console.log(JSON.stringify(createSuppressOutput()));
    return;
  }

  const rawInput = readHookInput();
  if (!rawInput.trim()) {
    console.log(JSON.stringify(createSuppressOutput()));
    return;
  }

  const payload = parseInput(rawInput);
  if (!payload) {
    console.log(JSON.stringify(createSuppressOutput()));
    return;
  }

  const prompt = extractPrompt(payload);
  if (!prompt || isSlashCommandPrompt(prompt)) {
    console.log(JSON.stringify(createSuppressOutput()));
    return;
  }

  const ownText = stripPastedContent(prompt);
  if (isAutoGeneratedPrompt(ownText) || isShortReaction(ownText)) {
    console.log(JSON.stringify(createSuppressOutput()));
    return;
  }

  const cleanText = sanitizeForKeywordDetection(prompt);
  if (!cleanText) {
    console.log(JSON.stringify(createSuppressOutput()));
    return;
  }

  const rules = loadRules(getRulesPath()).filter((rule) =>
    matchesPlatform(rule.platform, process.platform),
  );
  if (rules.length === 0) {
    console.log(JSON.stringify(createSuppressOutput()));
    return;
  }

  const compiledRules = compileRules(rules);
  if (compiledRules.length === 0) {
    console.log(JSON.stringify(createSuppressOutput()));
    return;
  }

  const matches = matchRules(compiledRules, cleanText);
  if (matches.length === 0) {
    console.log(JSON.stringify(createSuppressOutput()));
    return;
  }

  const resolvedMatches = resolveConflicts(matches);
  if (resolvedMatches.length === 0) {
    console.log(JSON.stringify(createSuppressOutput()));
    return;
  }

  const baseDir =
    typeof payload.cwd === "string" && payload.cwd
      ? payload.cwd
      : typeof payload.directory === "string" && payload.directory
        ? payload.directory
        : process.cwd();

  const skillRoots = defaultSkillRoots(baseDir);
  const scopedMatches = resolvedMatches
    .filter((match) => matchesRepoScope(baseDir, match.repo_scope))
    .map((match) => {
      if (!match.skill_candidates?.length) return match;
      const skill = resolveInstalledSkill(match.skill_candidates, skillRoots);
      return skill ? { ...match, skill } : null;
    })
    .filter(Boolean);
  const selected = selectPrimaryMatch(scopedMatches);
  if (!selected) {
    console.log(JSON.stringify(createSuppressOutput()));
    return;
  }

  activateState(baseDir, selected.state, prompt, payload);

  if (selected.action === "context_hint" && selected.hint) {
    console.log(
      JSON.stringify(createHookOutput(createContextHintOutput(selected))),
    );
    return;
  }

  if (selected.action === "suppress_omc") {
    console.log(
      JSON.stringify(createHookOutput(createSuppressOmcContext(selected))),
    );
    return;
  }

  if (selected.skill) {
    const context =
      selected.strength === "suggest"
        ? createSkillSuggestion(selected)
        : createSkillContext(selected);
    console.log(JSON.stringify(createHookOutput(context)));
    return;
  }

  if (selected.mcp_route) {
    console.log(
      JSON.stringify(createHookOutput(createMcpRouteContext(selected))),
    );
    return;
  }

  console.log(JSON.stringify(createSuppressOutput()));
}

// 훅 실행(node scripts/keyword-detector.mjs)일 때만 main 구동 — 테스트 import 시
// stdin 대기로 행이 걸리지 않도록 direct-run 가드.
const isDirectRun = (() => {
  try {
    if (typeof process.argv[1] !== "string" || !process.argv[1]) return false;
    const selfPath = fileURLToPath(import.meta.url);
    const argvPath = resolve(process.argv[1]);
    if (selfPath === argvPath) return true;
    // 심링크 설치 경로: argv[1]이 심링크면 import.meta.url(실경로)과 어긋난다.
    // canonical 경로로 재비교 (realpath 실패 시 non-direct 취급).
    return selfPath === realpathSync(argvPath);
  } catch {
    return false;
  }
})();

if (isDirectRun) {
  try {
    main();
  } catch (error) {
    console.error(`[triflux-keyword-detector] 예외 발생: ${error.message}`);
    console.log(JSON.stringify(createSuppressOutput()));
  }
}
